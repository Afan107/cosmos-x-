import React, { useState, useEffect } from 'react';
import {
  Cpu,
  Sparkles,
  AlertOctagon,
  Flame,
  Radio,
  FileText,
  Share2,
  CheckCircle2,
  RefreshCw,
  Search,
  Orbit,
  Zap,
  Sliders,
  ShieldCheck,
  Copy,
  Download,
  Rocket,
  Play,
  Layers,
} from 'lucide-react';
import {
  fetchOrSynthesizeObservationalStream,
  runAutonomousMLScan,
  IngestedTargetStream,
  PCALightCurveResult,
  MLDiscoveryBreakthrough,
} from '../../engine/aiDiscoveryPipeline';
import {
  STELLA_CORES,
  runStellaSyndicateAudit,
  NobelDiscoveryDossier,
} from '../../engine/stellaCoreEngine';
import { soundFX } from '../ui/AudioFeedback';

interface AIDiscoveryPipelineHUDProps {
  initialTargetId?: string;
  onDeployRover?: (targetId: string) => void;
  onSelectTarget?: (targetId: string) => void;
}

export default function AIDiscoveryPipelineHUD({
  initialTargetId = 'TIC-25155310',
  onDeployRover,
  onSelectTarget,
}: AIDiscoveryPipelineHUDProps) {
  const [targetInput, setTargetInput] = useState(initialTargetId);
  const [activeTargetId, setActiveTargetId] = useState(initialTargetId);
  const [sector, setSector] = useState(65);
  const [isScanning, setIsScanning] = useState(false);
  const [scanNotice, setScanNotice] = useState<string | null>(null);

  // Stream & Scan data
  const [stream, setStream] = useState<IngestedTargetStream>(() =>
    fetchOrSynthesizeObservationalStream(initialTargetId, 65)
  );

  const [scanResults, setScanResults] = useState<{
    pcaResult: PCALightCurveResult;
    breakthroughs: MLDiscoveryBreakthrough[];
    topSigma: number;
    isNobelTriggered: boolean;
  }>(() => runAutonomousMLScan(fetchOrSynthesizeObservationalStream(initialTargetId, 65)));

  // Selected breakthrough for Nobel dossier
  const [selectedBreakthrough, setSelectedBreakthrough] = useState<MLDiscoveryBreakthrough>(
    () => scanResults.breakthroughs[0]
  );

  // Active Nobel Dossier generated by the 7 Stella-Core minds
  const [activeDossier, setActiveDossier] = useState<NobelDiscoveryDossier | null>(() => {
    return runStellaSyndicateAudit({
      id: scanResults.breakthroughs[0]?.id || 'ANOM-01',
      targetId: initialTargetId,
      type: scanResults.breakthroughs[0]?.phenomenon || 'DYSON_SWARM_ASYMMETRIC',
      snr: scanResults.breakthroughs[0]?.snr || 29.8,
      measuredSigma: scanResults.breakthroughs[0]?.statisticalSigma || 7.6,
    });
  });

  const [showPreprintModal, setShowPreprintModal] = useState(false);
  const [copiedSeal, setCopiedSeal] = useState(false);

  // Run ML Scan
  const handleExecuteScan = (newTarget?: string) => {
    const tgt = newTarget || targetInput.trim() || activeTargetId;
    soundFX.triggerTick();
    setIsScanning(true);
    setScanNotice(`Ingesting observational stream for ${tgt} & running BLS + PCA pipeline...`);

    setTimeout(() => {
      const newStream = fetchOrSynthesizeObservationalStream(tgt, sector);
      setStream(newStream);

      const results = runAutonomousMLScan(newStream, tgt);
      setScanResults(results);
      setActiveTargetId(tgt);

      if (results.breakthroughs.length > 0) {
        setSelectedBreakthrough(results.breakthroughs[0]);
        const dossier = runStellaSyndicateAudit({
          id: results.breakthroughs[0].id,
          targetId: tgt,
          type: results.breakthroughs[0].phenomenon,
          snr: results.breakthroughs[0].snr,
          measuredSigma: results.breakthroughs[0].statisticalSigma,
        });
        setActiveDossier(dossier);
      }

      setIsScanning(false);

      if (results.isNobelTriggered) {
        soundFX.triggerRedAlertKlaxon();
        setScanNotice(`🚨 NOBEL BREAKTHROUGH CONFIRMED (> 7.0σ) for ${tgt}! 7 Stella-Cores synchronized.`);
      } else {
        soundFX.triggerPingSweep();
        setScanNotice(`ML Scan Complete for ${tgt}: Converged on ${results.topSigma}σ significance.`);
      }

      setTimeout(() => setScanNotice(null), 5500);
    }, 750);
  };

  const handleCopyLatex = () => {
    if (!activeDossier) return;
    navigator.clipboard.writeText(activeDossier.arxivPreprintLatex);
    setCopiedSeal(true);
    soundFX.triggerTick();
    setTimeout(() => setCopiedSeal(false), 2500);
  };

  return (
    <div className="flex h-full w-full flex-col gap-3 overflow-y-auto font-mono text-slate-200 p-1">
      {/* FLASHING RED ALERT BANNER WHEN SIGMA >= 7.0 */}
      {scanResults.isNobelTriggered && (
        <div className="rounded-xl border-2 border-rose-500 bg-rose-950/90 p-3 shadow-[0_0_35px_rgba(244,63,94,0.45)] flex items-center justify-between animate-pulse">
          <div className="flex items-center gap-3">
            <div className="h-4 w-4 rounded-full bg-rose-400 animate-ping" />
            <div className="flex items-center gap-2">
              <AlertOctagon size={18} className="text-rose-300" />
              <span className="font-extrabold text-white text-xs sm:text-sm uppercase tracking-wider">
                NOBEL-TIER BREAKTHROUGH CONFIRMED ({scanResults.topSigma}σ &ge; 7.0σ) &bull; VEGAPUNK SYNDICATE SYNCHRONIZED
              </span>
            </div>
          </div>
          <button
            type="button"
            onClick={() => {
              soundFX.triggerTick();
              setShowPreprintModal(true);
            }}
            className="px-3 py-1.5 rounded-lg bg-rose-600 hover:bg-rose-500 text-white font-bold text-xs shadow-[0_0_15px_rgba(244,63,94,0.6)] cursor-pointer transition-all whitespace-nowrap"
          >
            📜 View Nobel Dossier &amp; arXiv LaTeX
          </button>
        </div>
      )}

      {/* Target & NASA Observational Telemetry Stream Bar */}
      <div className="rounded-xl border border-purple-900/60 bg-[#070412]/90 p-3 backdrop-blur-xl flex flex-wrap items-center justify-between gap-2.5">
        <div className="flex items-center gap-2.5">
          <div className="h-7 w-7 rounded-lg bg-purple-950/80 border border-purple-700/60 flex items-center justify-center text-purple-300">
            <Cpu size={16} />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <span className="text-xs font-bold uppercase text-purple-200 tracking-wider">
                AI DISCOVERY PIPELINE &bull; NASA TAP &amp; MAST INGESTION
              </span>
              <span className="rounded bg-cyan-950/80 border border-cyan-700/60 px-1.5 py-0.2 text-[9px] text-cyan-300 font-bold">
                2-MIN TESS CADENCE
              </span>
            </div>
            <div className="text-[9px] text-slate-400">
              Box Least Squares (BLS) &bull; Principal Component Analysis (PCA) &bull; 7.0σ Nobel Filter
            </div>
          </div>
        </div>

        {/* Input Bar */}
        <div className="flex items-center gap-1.5 flex-1 max-w-lg">
          <div className="relative flex-1">
            <Search size={12} className="absolute left-2.5 top-1/2 -translate-y-1/2 text-purple-400" />
            <input
              type="text"
              value={targetInput}
              onChange={(e) => setTargetInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter') handleExecuteScan();
              }}
              placeholder="Input target (e.g. TIC 25155310, TOI-700, Kepler-452, Alcubierre Warp)..."
              className="w-full bg-black/80 border border-purple-900/60 rounded-xl pl-7 pr-3 py-1.5 text-xs text-purple-100 placeholder-slate-500 focus:outline-none focus:border-cyan-400"
            />
          </div>

          <button
            type="button"
            onClick={() => handleExecuteScan()}
            disabled={isScanning}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-gradient-to-r from-purple-600 via-indigo-600 to-cyan-600 hover:from-purple-500 hover:to-cyan-500 text-white font-bold text-xs shadow-[0_0_15px_rgba(168,85,247,0.4)] cursor-pointer disabled:opacity-50 whitespace-nowrap"
          >
            <RefreshCw size={12} className={isScanning ? 'animate-spin' : ''} />
            <span>{isScanning ? 'SCANNING ML...' : 'RUN ML SCAN'}</span>
          </button>
        </div>

        {/* Preset Archetype Chips */}
        <div className="flex items-center gap-1 text-[9.5px]">
          <span className="text-slate-500 font-bold uppercase">ARCHETYPES:</span>
          {[
            { id: 'TIC-25155310', label: '🛸 Dyson Swarm' },
            { id: 'WARP-BUBBLE-01', label: '⚛️ Alcubierre Warp' },
            { id: 'Kepler-452 b', label: '🍎 Exomoon TTV' },
            { id: 'PROXIMA-SETI-01', label: '📡 1.42 GHz SETI' },
          ].map((chip) => (
            <button
              key={chip.id}
              type="button"
              onClick={() => {
                setTargetInput(chip.id);
                handleExecuteScan(chip.id);
              }}
              className="px-2 py-0.5 rounded bg-black/60 hover:bg-purple-950/60 border border-purple-950 text-slate-300 hover:text-white transition-colors cursor-pointer"
            >
              {chip.label}
            </button>
          ))}
        </div>
      </div>

      {/* Notice Banner */}
      {scanNotice && (
        <div className="rounded-lg bg-purple-950/70 border border-purple-600/60 px-3 py-1.5 text-xs text-amber-200 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Sparkles size={13} className="text-amber-400 animate-pulse" />
            <span>{scanNotice}</span>
          </div>
        </div>
      )}

      {/* Dual Panel: Left (PCA & ML Diagnostics) & Right (7 Stella-Core Vegapunk Tribunal) */}
      <div className="grid grid-cols-12 gap-3">
        {/* LEFT COLUMN: ML Algorithms & PCA Eigen-Component Visualizer (7 cols) */}
        <div className="col-span-12 lg:col-span-7 flex flex-col gap-3">
          {/* Light Curve & PCA Residual Display */}
          <div className="rounded-xl border border-purple-950/60 bg-[#070410]/90 p-3.5 backdrop-blur-xl flex flex-col gap-2.5">
            <div className="flex items-center justify-between border-b border-purple-950/60 pb-2">
              <div className="flex items-center gap-2">
                <Sliders size={13} className="text-cyan-400" />
                <span className="text-xs font-bold text-cyan-200">
                  PHOTOMETRIC PCA DECOMPOSITION ({stream.pointsCount} DATA POINTS)
                </span>
              </div>
              <span className="text-[9px] text-slate-400">
                SOURCE: <strong className="text-cyan-300">{stream.sourceMission}</strong> (SECTOR {stream.sectorNumber})
              </span>
            </div>

            {/* Simulated Light Curve SVG Track */}
            <div className="relative h-44 w-full rounded-lg bg-black/80 border border-purple-950/80 p-2 overflow-hidden flex flex-col justify-between">
              <div className="flex items-center justify-between text-[9px] text-slate-500 font-mono">
                <span>NORMALIZED FLUX (1.0000)</span>
                <span className="text-cyan-400">RESIDUAL PCA CLEANED SIGNAL</span>
              </div>

              {/* SVG Sparkline */}
              <svg className="h-28 w-full overflow-visible" preserveAspectRatio="none" viewBox="0 0 400 100">
                <line x1="0" y1="50" x2="400" y2="50" stroke="#334155" strokeWidth="0.8" strokeDasharray="3 3" />
                <polyline
                  fill="none"
                  stroke="#38bdf8"
                  strokeWidth="1.8"
                  points={scanResults.pcaResult.residualFluxes
                    .map((f, i) => `${i},${Math.max(5, Math.min(95, 50 + (1.0 - f) * 12000))}`)
                    .join(' ')}
                />
              </svg>

              <div className="flex items-center justify-between text-[9px] text-slate-500">
                <span>EPOCH 0d (TESS INGRESS)</span>
                <span className="text-amber-400 font-bold">ASYMMETRY: {selectedBreakthrough?.asymmetryIndexPct.toFixed(1)}%</span>
                <span>EPOCH 14d (EGRESS)</span>
              </div>
            </div>

            {/* 3 PCA Eigen-Components Breakdown */}
            <div className="grid grid-cols-3 gap-2 text-[9.5px]">
              {scanResults.pcaResult.pcaComponents.map((comp, idx) => (
                <div key={idx} className="rounded-lg bg-black/60 p-2 border border-purple-950 flex flex-col gap-1">
                  <div className="flex items-center justify-between text-slate-400">
                    <span className="truncate">{comp.name.split(':')[0]}</span>
                    <span className="text-cyan-300 font-bold">{comp.varianceExplainedPct}%</span>
                  </div>
                  <div className="text-[8.5px] text-slate-500 truncate">{comp.name.split(':')[1]}</div>
                  <div className="h-1 w-full bg-slate-900 rounded-full overflow-hidden">
                    <div
                      className="h-full bg-cyan-500 rounded-full"
                      style={{ width: `${comp.varianceExplainedPct}%` }}
                    />
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* Detected Breakthroughs List */}
          <div className="rounded-xl border border-purple-950/60 bg-[#070410]/90 p-3.5 backdrop-blur-xl flex flex-col gap-2.5">
            <div className="flex items-center justify-between border-b border-purple-950/60 pb-1.5">
              <span className="text-xs font-bold text-purple-200 uppercase tracking-wide">
                IDENTIFIED ASTROPHYSICAL BREAKTHROUGHS
              </span>
              <span className="text-[9.5px] text-emerald-400 font-bold">
                {scanResults.breakthroughs.length} CANDIDATES ISOLATED
              </span>
            </div>

            <div className="space-y-2">
              {scanResults.breakthroughs.map((b) => {
                const isSelected = selectedBreakthrough?.id === b.id;
                return (
                  <div
                    key={b.id}
                    onClick={() => {
                      soundFX.triggerTick();
                      setSelectedBreakthrough(b);
                      const dossier = runStellaSyndicateAudit({
                        id: b.id,
                        targetId: b.targetId,
                        type: b.phenomenon,
                        snr: b.snr,
                        measuredSigma: b.statisticalSigma,
                      });
                      setActiveDossier(dossier);
                    }}
                    className={`rounded-xl border p-3 flex flex-col gap-1.5 cursor-pointer transition-all ${
                      isSelected
                        ? 'border-cyan-500/80 bg-cyan-950/30 shadow-[0_0_20px_rgba(34,211,238,0.2)]'
                        : 'border-purple-950 bg-black/40 hover:border-purple-800'
                    }`}
                  >
                    <div className="flex items-center justify-between">
                      <div className="flex items-center gap-2">
                        <span className="text-base">
                          {b.phenomenon === 'ALCUBIERRE_WARP_METRIC'
                            ? '⚛️'
                            : b.phenomenon === 'DYSON_SWARM_ASYMMETRIC'
                            ? '🛸'
                            : b.phenomenon === 'EXOMOON_TRANSIT_TTV'
                            ? '🍎'
                            : '📡'}
                        </span>
                        <div>
                          <div className="text-xs font-bold text-white">{b.title}</div>
                          <div className="text-[9px] text-slate-400">
                            TARGET: <strong className="text-purple-300">{b.targetId}</strong> &bull; ALGORITHM: {b.detectionAlgorithm}
                          </div>
                        </div>
                      </div>

                      <div className="flex items-center gap-2">
                        <span
                          className={`px-2 py-0.5 rounded text-[10px] font-extrabold border ${
                            b.isNobelThreshold
                              ? 'bg-rose-950/80 text-rose-300 border-rose-600 shadow-[0_0_10px_rgba(244,63,94,0.4)]'
                              : 'bg-amber-950/80 text-amber-300 border-amber-600'
                          }`}
                        >
                          {b.statisticalSigma}σ {b.isNobelThreshold ? 'NOBEL GOLD' : 'ELEVATED'}
                        </span>
                      </div>
                    </div>

                    <div className="text-[10px] text-slate-300 leading-relaxed font-sans bg-black/50 p-2 rounded border border-purple-950/50">
                      {b.evidenceSummary}
                    </div>

                    <div className="flex items-center justify-between text-[9px] text-slate-400 pt-1 border-t border-purple-950/40">
                      <span>SNR: <strong className="text-cyan-300">{b.snr.toFixed(1)}</strong></span>
                      <span>PERIOD: <strong className="text-amber-300">{b.periodDays.toFixed(2)}d</strong></span>
                      <span>PROOF: <code className="text-purple-300">{b.mathematicalProofEq}</code></span>
                    </div>
                  </div>
                );
              })}
            </div>
          </div>
        </div>

        {/* RIGHT COLUMN: 7 Stella-Core Vegapunk Syndicate Peer-Review (5 cols) */}
        <div className="col-span-12 lg:col-span-5 flex flex-col gap-3">
          <div className="rounded-xl border border-purple-950/60 bg-[#070410]/90 p-3.5 backdrop-blur-xl flex flex-col gap-3">
            <div className="flex items-center justify-between border-b border-purple-950/60 pb-2">
              <div className="flex items-center gap-2">
                <span className="text-base">🧬</span>
                <div>
                  <div className="text-xs font-bold text-transparent bg-clip-text bg-gradient-to-r from-amber-300 via-purple-300 to-cyan-300">
                    7 STELLA-CORE VEGAPUNK SYNDICATE
                  </div>
                  <div className="text-[9px] text-slate-400">Autonomous Peer-Review Consensus Engine</div>
                </div>
              </div>

              <button
                type="button"
                onClick={() => {
                  soundFX.triggerNeuralSync();
                  handleExecuteScan();
                }}
                className="flex items-center gap-1 px-2.5 py-1 rounded-lg bg-purple-950/80 hover:bg-purple-900 border border-purple-700/60 text-purple-200 text-[10px] font-bold cursor-pointer"
              >
                <RefreshCw size={11} />
                <span>Re-Sync</span>
              </button>
            </div>

            {/* 7 Stella-Core Minds Evaluation Cards */}
            <div className="space-y-2 max-h-[460px] overflow-y-auto no-scrollbar pr-1">
              {activeDossier?.peerReviewVotes.map((vote) => {
                const mind = Object.values(STELLA_CORES).find((m) => m.id === vote.mindId);
                return (
                  <div
                    key={vote.mindId}
                    className="rounded-lg border border-purple-950/60 bg-black/60 p-2.5 flex flex-col gap-1.5 text-[9.5px]"
                  >
                    <div className="flex items-center justify-between">
                      <div className="flex items-center gap-1.5 font-bold">
                        <span className="text-sm">{vote.icon}</span>
                        <span className="text-slate-200">{vote.mindName}</span>
                      </div>
                      <span
                        className={`px-1.5 py-0.2 rounded text-[8px] font-bold border ${
                          vote.confidenceSigma >= 7.0
                            ? 'bg-rose-950 text-rose-300 border-rose-800'
                            : 'bg-emerald-950 text-emerald-300 border-emerald-800'
                        }`}
                      >
                        {vote.confidenceSigma}σ {vote.verdict.replace(/_/g, ' ')}
                      </span>
                    </div>

                    <div className="text-slate-300 italic font-sans leading-relaxed pl-1 text-[9px]">
                      &quot;{vote.scientificArgument}&quot;
                    </div>

                    <div className="flex items-center justify-between text-[8px] text-slate-400 pt-1 border-t border-purple-950/40">
                      <span>EQUATION: <code className="text-amber-300">{vote.proofEquation}</code></span>
                    </div>
                  </div>
                );
              })}
            </div>

            {/* Dossier Actions & SHA-256 Provenance */}
            {activeDossier && (
              <div className="space-y-2 pt-2 border-t border-purple-950/60">
                <div className="rounded bg-black/80 p-2 border border-purple-950 flex flex-col gap-1 text-[9px]">
                  <div className="flex items-center justify-between text-slate-400">
                    <span className="font-bold flex items-center gap-1">
                      <ShieldCheck size={11} className="text-emerald-400" />
                      <span>CRYPTOGRAPHIC SHA-256 SEAL:</span>
                    </span>
                    <span className="text-emerald-400 font-bold">VERIFIED BY PYTHAGORAS</span>
                  </div>
                  <div className="text-[8px] text-emerald-300 font-mono truncate">
                    {activeDossier.sha256Seal}
                  </div>
                </div>

                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={() => {
                      soundFX.triggerTick();
                      setShowPreprintModal(true);
                    }}
                    className="flex-1 flex items-center justify-center gap-1.5 py-2 rounded-xl bg-gradient-to-r from-amber-600 via-purple-600 to-indigo-600 hover:from-amber-500 hover:to-indigo-500 text-white font-bold text-xs shadow-[0_0_15px_rgba(245,158,11,0.35)] cursor-pointer"
                  >
                    <FileText size={13} />
                    <span>Generate Nobel Preprint (LaTeX)</span>
                  </button>

                  {onDeployRover && (
                    <button
                      type="button"
                      onClick={() => onDeployRover(activeTargetId)}
                      className="px-3 py-2 rounded-xl bg-cyan-950 hover:bg-cyan-900 border border-cyan-600 text-cyan-200 text-xs font-bold flex items-center gap-1 cursor-pointer"
                    >
                      <Rocket size={13} />
                      <span>Probe</span>
                    </button>
                  )}
                </div>
              </div>
            )}
          </div>
        </div>
      </div>

      {/* NOBEL DOSSIER & ARXIV PREPRINT MODAL */}
      {showPreprintModal && activeDossier && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-md p-4 animate-fade-in font-mono">
          <div className="w-full max-w-3xl rounded-2xl border border-amber-500/80 bg-[#070314]/98 p-5 shadow-[0_0_40px_rgba(245,158,11,0.35)] flex flex-col gap-3 text-xs max-h-[85vh]">
            <div className="flex items-center justify-between border-b border-amber-950 pb-2.5">
              <div className="flex items-center gap-2">
                <span className="text-xl">📜</span>
                <div>
                  <div className="font-extrabold text-amber-300 text-sm">
                    NOBEL BREAKTHROUGH DOSSIER &bull; ARXIV PREPRINT LATEX
                  </div>
                  <div className="text-[10px] text-slate-400">
                    Target: {activeDossier.targetId} &bull; Significance: {activeDossier.compositeSigma}σ
                  </div>
                </div>
              </div>

              <button
                type="button"
                onClick={() => setShowPreprintModal(false)}
                className="px-2.5 py-1 rounded-lg bg-black/60 border border-purple-900 text-slate-400 hover:text-white cursor-pointer"
              >
                Close [✕]
              </button>
            </div>

            {/* LaTeX Code Box */}
            <div className="relative flex-1 overflow-y-auto rounded-xl bg-black/90 border border-purple-950 p-3 font-mono text-[10px] text-slate-300 leading-relaxed max-h-[50vh]">
              <pre className="whitespace-pre-wrap">{activeDossier.arxivPreprintLatex}</pre>
            </div>

            {/* Footer with Copy and Download */}
            <div className="flex items-center justify-between pt-2 border-t border-purple-950/60">
              <div className="text-[9px] text-emerald-400 flex items-center gap-1 font-mono">
                <ShieldCheck size={12} />
                <span>{activeDossier.sha256Seal}</span>
              </div>

              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={handleCopyLatex}
                  className="flex items-center gap-1 px-3 py-1.5 rounded-lg bg-purple-950 hover:bg-purple-900 border border-purple-700 text-purple-200 text-xs font-bold cursor-pointer"
                >
                  <Copy size={12} />
                  <span>{copiedSeal ? 'Copied LaTeX!' : 'Copy LaTeX'}</span>
                </button>

                <button
                  type="button"
                  onClick={() => setShowPreprintModal(false)}
                  className="px-3 py-1.5 rounded-lg bg-amber-600 hover:bg-amber-500 text-white font-bold text-xs cursor-pointer"
                >
                  Confirm &amp; Publish
                </button>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
